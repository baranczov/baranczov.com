#!/usr/bin/env bash
# Run on the VPS as root. Keep copies outside the VPS for disaster recovery.
set -euo pipefail
umask 077
cd /opt/baranczov
backup_root=/opt/baranczov-backups
install -d -m 0700 "$backup_root"
backup_name="backup-$(date -u +%Y%m%dT%H%M%SZ)"
backup_dir="$backup_root/$backup_name"
mkdir -m 0700 -- "$backup_dir"
trap 'rm -rf -- "$backup_dir"' ERR
compose=(docker compose --env-file .env.production)
"${compose[@]}" exec -T db pg_dump -U portfolio -d portfolio --format=custom > "$backup_dir/database.dump"
"${compose[@]}" exec -T web tar -czf - -C /app/media . > "$backup_dir/media.tar.gz"
cp .env.production compose.yaml "$backup_dir/"
cp deploy/Caddyfile "$backup_dir/"
(cd "$backup_dir" && sha256sum database.dump media.tar.gz .env.production compose.yaml Caddyfile > SHA256SUMS)
touch "$backup_dir/COMPLETE"
trap - ERR
# Retain only completed backups generated by this script, for 14 days.
find "$backup_root" -mindepth 2 -maxdepth 2 -type f -name COMPLETE -mtime +14 -print0 |
    while IFS= read -r -d '' marker; do
        candidate="$(dirname "$marker")"
        case "$(basename "$candidate")" in
            backup-[0-9]*T[0-9]*Z) rm -rf -- "$candidate" ;;
        esac
    done
printf 'Backup created: %s\n' "$backup_dir"
